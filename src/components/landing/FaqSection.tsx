import * as React from 'react';
import { ChevronDown, HelpCircle } from 'lucide-react';
import { cn } from '@/lib/utils';

interface FaqItem {
  id: string;
  question: string;
  answer: React.ReactNode;
}

const FAQ_ITEMS: FaqItem[] = [
  {
    id: 'faq-what-is-intelcode',
    question: 'What is IntelCode?',
    answer: (
      <p>
        IntelCode is an engineering intelligence platform that indexes code repositories, Git history, pull requests, issues, and documentation into a searchable knowledge base. Developers can explore symbols, trace historical implementation rationale, and ask natural-language questions grounded strictly in retrieved repository code.
      </p>
    ),
  },
  {
    id: 'faq-how-indexing-works',
    question: 'How does repository indexing work?',
    answer: (
      <p>
        When you connect a repository, IntelCode traverses the Git tree using GitHub’s Git Data API, filters out binary files and credentials, and parses source files using language-aware AST chunking (functions, classes, interfaces, and methods). It then computes SHA-256 chunk hashes and indexes the code using 512-dimensional Voyage Code 4 vector embeddings stored in Supabase PostgreSQL with pgvector.
      </p>
    ),
  },
  {
    id: 'faq-semantic-search',
    question: 'How does hybrid semantic search work?',
    answer: (
      <p>
        IntelCode combines 512-dimensional vector cosine similarity via pgvector HNSW indexing with PostgreSQL Full-Text Search. The system ranks results using Reciprocal Rank Fusion (RRF), ensuring that both semantic conceptual matches and exact identifier/symbol names are retrieved accurately.
      </p>
    ),
  },
  {
    id: 'faq-private-repos',
    question: 'How does IntelCode handle private repositories and security?',
    answer: (
      <p>
        Private repositories are accessed via user-authorized GitHub OAuth tokens passed to serverless functions. Secrets, private keys, environment files (<code className="text-intel-text font-mono text-xs">.env*</code>), and build artifacts are strictly excluded before indexing. All database queries enforce PostgreSQL Row Level Security (RLS), ensuring cross-tenant isolation.
      </p>
    ),
  },
  {
    id: 'faq-grounded-answers',
    question: 'How does the AI answer questions without fabricating citations?',
    answer: (
      <p>
        Queries are first embedded with Voyage Code 4 (<code className="text-intel-text font-mono text-xs">input_type: "query"</code>) and matched against indexed chunks. The retrieved evidence is passed to Google Gemini with strict prompt constraints forbidding unsupported assertions. If context is missing, the AI explicitly reports insufficient repository evidence rather than guessing.
      </p>
    ),
  },
  {
    id: 'faq-source-citations',
    question: 'What are interactive source citations?',
    answer: (
      <p>
        Every generated answer includes verified reference chips citing the relative file path, line boundaries (e.g., lines 11–48), and commit SHA. Clicking a citation navigates directly to the embedded Monaco editor with the cited lines highlighted.
      </p>
    ),
  },
  {
    id: 'faq-differential-reindexing',
    question: 'How does differential reindexing work?',
    answer: (
      <p>
        IntelCode compares Git blob SHAs from GitHub against previously stored file records. Files whose Git SHAs have not changed take 0ms to re-index, while only modified and newly added files are downloaded, chunked, and embedded. Existing chunks remain searchable while an update is underway.
      </p>
    ),
  },
  {
    id: 'faq-technologies-stack',
    question: 'What technologies power IntelCode?',
    answer: (
      <p>
        The frontend is built with React 18, TypeScript, Vite, Tailwind CSS, and Monaco Editor. The backend runs on Vercel Serverless Functions with Node.js. Persistent storage and vector search use Supabase PostgreSQL and pgvector. Embeddings are generated by Voyage AI’s <code className="text-intel-text font-mono text-xs">voyage-code-4</code> (512 dimensions), and grounded reasoning is powered by Google Gemini.
      </p>
    ),
  },
];

export function FaqSection() {
  const [openIds, setOpenIds] = React.useState<Set<string>>(new Set(['faq-what-is-intelcode']));

  const toggleItem = (id: string) => {
    setOpenIds((prev) => {
      const next = new Set(prev);
      if (next.has(id)) {
        next.delete(id);
      } else {
        next.add(id);
      }
      return next;
    });
  };

  return (
    <section
      id="faq"
      aria-labelledby="faq-heading"
      className="py-20 px-4 sm:px-6 lg:px-8 border-t border-intel-border/60 bg-intel-surface/20"
    >
      <div className="max-w-4xl mx-auto space-y-10">
        <div className="text-center space-y-2.5">
          <span className="text-xs font-mono font-semibold text-intel-accent uppercase tracking-wider inline-flex items-center gap-1.5">
            <HelpCircle className="w-4 h-4" />
            Frequently Asked Questions
          </span>
          <h2 id="faq-heading" className="text-2xl sm:text-3xl font-bold tracking-tight text-intel-text">
            Everything You Need to Know About IntelCode
          </h2>
          <p className="text-sm text-intel-text-secondary max-w-xl mx-auto">
            Technical answers about indexing, code-aware chunking, hybrid vector retrieval, and data security.
          </p>
        </div>

        <div className="space-y-3">
          {FAQ_ITEMS.map((item) => {
            const isOpen = openIds.has(item.id);
            const contentId = `${item.id}-content`;
            const headerId = `${item.id}-header`;

            return (
              <div
                key={item.id}
                className={cn(
                  'rounded-lg border border-intel-border bg-intel-surface transition-all duration-150 overflow-hidden',
                  isOpen && 'border-intel-border-strong shadow-subtle'
                )}
              >
                <h3>
                  <button
                    id={headerId}
                    type="button"
                    aria-expanded={isOpen}
                    aria-controls={contentId}
                    onClick={() => toggleItem(item.id)}
                    className="w-full flex items-center justify-between p-4 sm:p-5 text-left text-sm sm:text-base font-medium text-intel-text hover:text-intel-accent focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-intel-accent select-none transition-colors"
                  >
                    <span>{item.question}</span>
                    <ChevronDown
                      className={cn(
                        'w-4 h-4 text-intel-muted shrink-0 transition-transform duration-200 ml-4',
                        isOpen && 'transform rotate-180 text-intel-accent'
                      )}
                      aria-hidden="true"
                    />
                  </button>
                </h3>
                <div
                  id={contentId}
                  role="region"
                  aria-labelledby={headerId}
                  hidden={!isOpen}
                  className={cn(
                    'px-4 sm:px-5 pb-4 sm:pb-5 text-xs sm:text-sm text-intel-text-secondary leading-relaxed space-y-2 border-t border-intel-border/40 pt-3 animate-fade-in',
                    !isOpen && 'hidden'
                  )}
                >
                  {item.answer}
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
}
